SET LIST ON;

SELECT 'CUSTOMERS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM CUSTOMERS;
SELECT 'PRODUCTS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM PRODUCTS;
SELECT 'ORDERS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM ORDERS;
SELECT 'ORDER_ITEMS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM ORDER_ITEMS;
SELECT 'PRODUCT_REVIEWS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM PRODUCT_REVIEWS;
SELECT 'AUDIT_LOG' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM AUDIT_LOG;

SELECT COUNT(*) AS ORPHAN_ORDERS
FROM ORDERS O
LEFT JOIN CUSTOMERS C ON C.CUSTOMER_ID = O.CUSTOMER_ID
WHERE C.CUSTOMER_ID IS NULL;

SELECT COUNT(*) AS ORPHAN_ORDER_ITEMS
FROM ORDER_ITEMS I
LEFT JOIN ORDERS O ON O.ORDER_ID = I.ORDER_ID
WHERE O.ORDER_ID IS NULL;

SELECT COUNT(*) AS ORPHAN_ORDER_ITEM_PRODUCTS
FROM ORDER_ITEMS I
LEFT JOIN PRODUCTS P ON P.PRODUCT_ID = I.PRODUCT_ID
WHERE P.PRODUCT_ID IS NULL;

SELECT COUNT(*) AS ORPHAN_REVIEWS
FROM PRODUCT_REVIEWS R
LEFT JOIN PRODUCTS P ON P.PRODUCT_ID = R.PRODUCT_ID
WHERE P.PRODUCT_ID IS NULL;

SELECT COUNT(*) AS NON_NULL_REVIEWS
FROM PRODUCT_REVIEWS
WHERE REVIEW_TEXT IS NOT NULL;

SELECT TRIM(RDB$TABLESPACE_NAME) AS TABLESPACE_NAME
FROM RDB$TABLESPACES
WHERE TRIM(RDB$TABLESPACE_NAME) IN ('TS_DATA', 'TS_INDEX', 'TS_ARCHIVE')
ORDER BY 1;

SELECT TRIM(RDB$RELATION_NAME) AS TABLE_NAME,
       TRIM(RDB$TABLESPACE_NAME) AS TABLESPACE_NAME
FROM RDB$RELATIONS
WHERE COALESCE(RDB$SYSTEM_FLAG, 0) = 0
  AND RDB$VIEW_BLR IS NULL
  AND TRIM(RDB$RELATION_NAME) IN (
      'CUSTOMERS', 'PRODUCTS', 'ORDERS', 'ORDER_ITEMS',
      'PRODUCT_REVIEWS', 'AUDIT_LOG'
  )
ORDER BY 1;

SELECT TRIM(RDB$INDEX_NAME) AS INDEX_NAME,
       TRIM(RDB$TABLESPACE_NAME) AS TABLESPACE_NAME
FROM RDB$INDICES
WHERE COALESCE(RDB$SYSTEM_FLAG, 0) = 0
ORDER BY 1;
